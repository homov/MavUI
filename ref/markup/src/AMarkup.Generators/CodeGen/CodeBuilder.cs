using System;
using System.Collections.Generic;
using System.Linq;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;

namespace AMarkup.Generators.CodeGen;

public sealed class CodeBuilder
{
	private const string DefaultAutoGeneratedMessage = "This code was generated.\r\n\r\nChanges to this file may cause incorrect behavior and will be lost if\r\nthe code is regenerated.";

	private string? _autoGeneratedMessage;

	private readonly List<string> _namespaceImports = new List<string>();

	private readonly List<string> _assemblyAttributes = new List<string>();

	private readonly Queue<IBuilder> _builders = new Queue<IBuilder>();

	private bool _topLevel;

	private NullableState _nullable;

	public string? Namespace { get; }

	public IndentStyle IndentStyle { get; }

	public IReadOnlyList<ClassBuilder> Classes => _builders.OfType<ClassBuilder>().ToList();

	public IReadOnlyList<RecordBuilder> Records => _builders.OfType<RecordBuilder>().ToList();

	public IReadOnlyList<EnumBuilder> Enums => _builders.OfType<EnumBuilder>().ToList();

	public IReadOnlyList<DelegateBuilder> Delegates => _builders.OfType<DelegateBuilder>().ToList();

	private CodeBuilder(string? clrNamespace = null, IndentStyle indentStyle = IndentStyle.Spaces)
	{
		Namespace = clrNamespace;
		IndentStyle = indentStyle;
	}

	public CodeBuilder TopLevelNamespace()
	{
		return TopLevelNamespace(topLevel: true);
	}

	public CodeBuilder TopLevelNamespace(bool topLevel)
	{
		_topLevel = topLevel;
		return this;
	}

	public CodeBuilder Nullable()
	{
		return Nullable(NullableState.Enable);
	}

	public CodeBuilder Nullable(NullableState nullable)
	{
		_nullable = nullable;
		return this;
	}

	public static CodeBuilder CreateInGlobalNamespace(IndentStyle indentStyle = IndentStyle.Spaces)
	{
		return new CodeBuilder(null, indentStyle).TopLevelNamespace();
	}

	public static CodeBuilder Create(string clrNamespace, IndentStyle indentStyle = IndentStyle.Spaces)
	{
		return new CodeBuilder(clrNamespace, indentStyle);
	}

	public static CodeBuilder Create(INamespaceSymbol namespaceSymbol, IndentStyle indentStyle = IndentStyle.Spaces)
	{
		return Create(namespaceSymbol.ToString(), indentStyle);
	}

	public static ClassBuilder Create(ITypeSymbol typeSymbol, IndentStyle indentStyle = IndentStyle.Spaces)
	{
		return Create(typeSymbol.ContainingNamespace, indentStyle).AddClass(typeSymbol.Name).WithAccessModifier(typeSymbol.DeclaredAccessibility).OfType(typeSymbol.TypeKind);
	}

	public CodeBuilder AddNamespaceImport(string importedNamespace)
	{
		string item = Regex.Replace(importedNamespace, "^using\\w+", string.Empty).Replace(";", string.Empty);
		if (!_namespaceImports.Contains(item))
		{
			_namespaceImports.Add(item);
		}
		return this;
	}

	public CodeBuilder AddNamespaceImport(ISymbol symbol)
	{
		return AddNamespaceImport(symbol.ContainingNamespace.ToString());
	}

	public CodeBuilder AddNamespaceImport(INamespaceSymbol symbol)
	{
		return AddNamespaceImport(symbol.ToString());
	}

	public CodeBuilder AddAssemblyAttribute(string attribute)
	{
		_assemblyAttributes.Add(attribute);
		return this;
	}

	public ClassBuilder AddClass(string name)
	{
		ClassBuilder classBuilder = new ClassBuilder(name, this);
		_builders.Enqueue(classBuilder);
		return classBuilder;
	}

	public ClassBuilder AddClass(ITypeSymbol symbol)
	{
		return AddClass(symbol.Name);
	}

	internal ClassBuilder AddClass(ClassBuilder builder)
	{
		_builders.Enqueue(builder);
		builder.Builder = this;
		return builder;
	}

	public RecordBuilder AddRecord(string name)
	{
		RecordBuilder recordBuilder = new RecordBuilder(name, this);
		_builders.Enqueue(recordBuilder);
		return recordBuilder;
	}

	internal RecordBuilder AddRecord(RecordBuilder builder)
	{
		_builders.Enqueue(builder);
		builder.Builder = this;
		return builder;
	}

	public EnumBuilder AddEnum(string name)
	{
		EnumBuilder enumBuilder = new EnumBuilder(name, this);
		_builders.Enqueue(enumBuilder);
		return enumBuilder;
	}

	internal EnumBuilder AddEnum(EnumBuilder builder)
	{
		_builders.Enqueue(builder);
		builder.Builder = this;
		return builder;
	}

	public DelegateBuilder AddDelegate(string name)
	{
		DelegateBuilder delegateBuilder = new DelegateBuilder(name, this);
		_builders.Enqueue(delegateBuilder);
		return delegateBuilder;
	}

	public CodeBuilder WithAutoGeneratedMessage(string message)
	{
		_autoGeneratedMessage = message;
		return this;
	}

	public void Clear()
	{
		_namespaceImports.Clear();
		_assemblyAttributes.Clear();
		_builders.Clear();
	}

	private CodeWriter BuildInternal()
	{
		CodeWriter writer = new CodeWriter(IndentStyle);
		writer.AppendLine("//------------------------------------------------------------------------------");
		writer.AppendLine("// <auto-generated>");
		string[] array = Regex.Replace(string.IsNullOrEmpty(_autoGeneratedMessage) ? "This code was generated.\r\n\r\nChanges to this file may cause incorrect behavior and will be lost if\r\nthe code is regenerated." : _autoGeneratedMessage, "\\r\\n", "\n").Split(new char[1] { '\n' });
		foreach (string text in array)
		{
			writer.AppendLine(("//     " + text).Trim());
		}
		writer.AppendLine("// </auto-generated>");
		writer.AppendLine("//------------------------------------------------------------------------------");
		writer.NewLine();
		List<string> namespaces = _namespaceImports.Distinct().ToList();
		IEnumerable<string> imports = GetImports(ref namespaces, (string x) => x.StartsWith("System"));
		IEnumerable<string> imports2 = GetImports(ref namespaces, (string x) => !x.StartsWith("System") && !x.Contains("=") && !x.Contains("static"));
		IEnumerable<string> imports3 = GetImports(ref namespaces, (string x) => x.Contains("="));
		WriteNamespace(imports, ref writer);
		WriteNamespace(imports2, ref writer);
		WriteNamespace(imports3, ref writer);
		WriteNamespace(namespaces, ref writer);
		if (_namespaceImports.Count > 0)
		{
			writer.NewLine();
		}
		if (_nullable != NullableState.Default)
		{
			writer.AppendLine($"#nullable {_nullable}".ToLowerInvariant());
		}
		WriteAssemblyAttributes(_assemblyAttributes, ref writer);
		if (_topLevel)
		{
			if (Namespace != null)
			{
				writer.AppendLine("namespace " + Namespace + ";");
				writer.NewLine();
			}
			WriteBody(writer);
			return writer;
		}
		using (writer.Block("namespace " + Namespace))
		{
			WriteBody(writer);
			return writer;
		}
	}

	private void WriteBody(CodeWriter writer)
	{
		Queue<IBuilder> queue = new Queue<IBuilder>(_builders);
		while (queue.Any())
		{
			queue.Dequeue().Write(in writer);
			if (queue.Any())
			{
				writer.NewLine();
			}
		}
	}

	private static IEnumerable<string> GetImports(ref List<string> namespaces, Func<string, bool> predicate)
	{
		string[] array = namespaces.Where(predicate).ToArray();
		string[] array2 = array;
		foreach (string item in array2)
		{
			namespaces.Remove(item);
		}
		return array.OrderBy((string x) => x);
	}

	public string Build()
	{
		return BuildInternal().Render();
	}

	public override string ToString()
	{
		return Build();
	}

	private static void WriteAssemblyAttributes(IEnumerable<string> assemblyAttributes, ref CodeWriter writer)
	{
		if (!assemblyAttributes.Any())
		{
			return;
		}
		foreach (string item in from x in assemblyAttributes.Distinct()
			orderby x
			select x)
		{
			if (!string.IsNullOrEmpty(item))
			{
				string text = item;
				if (item[0] != '[' || !item.StartsWith("[assembly:"))
				{
					text = "[assembly: " + item + "]";
				}
				text = text.Replace("[[", "[").Replace("]]", "]");
				writer.AppendLine(text);
			}
		}
	}

	private static void WriteNamespace(IEnumerable<string> namespaces, ref CodeWriter writer)
	{
		foreach (string @namespace in namespaces)
		{
			writer.AppendLine("using " + @namespace + ";");
		}
	}
}
